//! Helpers for tests that need external tools (dpkg-deb, gpg, ...).

use std::path::{Path, PathBuf};
use std::process::Command;

/// Called when a test cannot run because a tool is missing. With
/// `APTPOD_REQUIRE_TOOLS=1` (set in CI) this fails the test instead of
/// letting it pass vacuously.
pub fn missing_tool(tool: &str) {
    if std::env::var("APTPOD_REQUIRE_TOOLS").is_ok_and(|v| v == "1") {
        panic!("{tool} is required (APTPOD_REQUIRE_TOOLS=1)");
    }
    eprintln!("skipping: {tool} not installed");
}

pub fn have(tool: &str) -> bool {
    let ok = Command::new(tool).arg("--version").output().is_ok();
    if !ok {
        missing_tool(tool);
    }
    ok
}

/// Builds a `.deb` with dpkg-deb. `compression` is gzip, xz, zstd or none.
pub fn build_deb(
    dir: &Path,
    name: &str,
    version: &str,
    arch: &str,
    compression: &str,
    extra: &str,
) -> PathBuf {
    let root = dir.join(format!("build-{name}-{version}-{arch}-{compression}"));
    std::fs::create_dir_all(root.join("DEBIAN")).unwrap();
    std::fs::create_dir_all(root.join("usr/share").join(name)).unwrap();
    std::fs::write(
        root.join("DEBIAN/control"),
        format!(
            "Package: {name}\nVersion: {version}\nArchitecture: {arch}\nMaintainer: Test <test@example.invalid>\nSection: misc\nPriority: optional\n{extra}Description: test package {name}\n generated by aptpod tests\n"
        ),
    )
    .unwrap();
    std::fs::write(
        root.join("usr/share").join(name).join("marker"),
        format!("{name} {version}\n"),
    )
    .unwrap();
    let out = dir.join(format!("{name}_{version}_{arch}-{compression}.deb"));
    let st = Command::new("dpkg-deb")
        .args(["--root-owner-group", &format!("-Z{compression}"), "--build"])
        .arg(&root)
        .arg(&out)
        .output()
        .unwrap();
    assert!(
        st.status.success(),
        "dpkg-deb: {}",
        String::from_utf8_lossy(&st.stderr)
    );
    out
}

/// A throwaway gpg key (ed25519, with a passphrase) in a short-lived home.
pub struct TestKey {
    pub home: tempfile::TempDir,
    pub fpr: String,
    pub passphrase_file: PathBuf,
    /// Binary public key, as apt's `signed-by` wants it.
    pub public: Vec<u8>,
}

impl TestKey {
    pub fn new() -> Option<Self> {
        if !have("gpg") {
            return None;
        }
        // short path: gpg-agent socket names are length limited
        let home = tempfile::Builder::new()
            .prefix("apk")
            .tempdir_in("/tmp")
            .unwrap();
        std::fs::set_permissions(
            home.path(),
            std::os::unix::fs::PermissionsExt::from_mode(0o700),
        )
        .unwrap();
        let passphrase_file = home.path().join("pass");
        std::fs::write(&passphrase_file, "s3cret-test\n").unwrap();
        let gpg = |args: &[&str]| {
            let out = Command::new("gpg")
                .arg("--homedir")
                .arg(home.path())
                .arg("--batch")
                .args(args)
                .output()
                .unwrap();
            assert!(
                out.status.success(),
                "gpg {args:?}: {}",
                String::from_utf8_lossy(&out.stderr)
            );
            out.stdout
        };
        let pass = passphrase_file.to_str().unwrap();
        gpg(&[
            "--pinentry-mode",
            "loopback",
            "--passphrase-file",
            pass,
            "--quick-gen-key",
            "aptpod test <test@example.invalid>",
            "ed25519",
            "sign",
            "never",
        ]);
        let list = String::from_utf8(gpg(&["--with-colons", "--list-secret-keys"])).unwrap();
        let fpr = list
            .lines()
            .find(|l| l.starts_with("fpr:"))
            .unwrap()
            .split(':')
            .nth(9)
            .unwrap()
            .to_string();
        let public = gpg(&["--export", &fpr]);
        Some(Self {
            home,
            fpr,
            passphrase_file,
            public,
        })
    }

    pub fn signer(&self) -> crate::sign::GpgSigner {
        let mut s = crate::sign::GpgSigner::new(self.fpr.clone());
        s.homedir = Some(self.home.path().to_path_buf());
        s.passphrase_file = Some(self.passphrase_file.clone());
        s
    }
}

impl Drop for TestKey {
    fn drop(&mut self) {
        let _ = Command::new("gpgconf")
            .arg("--homedir")
            .arg(self.home.path())
            .args(["--kill", "all"])
            .status();
    }
}
