//! Helpers for the end-to-end tests: the real server and CLI binaries, test
//! upstreams (HTTP, rsync), packages and keys.
#![allow(dead_code)]

use std::io::{BufRead, BufReader, Write};
use std::path::{Path, PathBuf};
use std::process::{Child, Command, Output, Stdio};
use std::sync::mpsc;
use std::time::Duration;

use serde_json::Value;

pub fn require(what: &str) {
    if std::env::var("APTPOD_REQUIRE_TOOLS").is_ok_and(|v| v == "1") {
        panic!("{what} is required (APTPOD_REQUIRE_TOOLS=1)");
    }
    eprintln!("skipping: {what} not available");
}

pub fn build_deb(dir: &Path, name: &str, version: &str) -> PathBuf {
    build_deb_marked(dir, name, version, version)
}

pub fn build_deb_marked(dir: &Path, name: &str, version: &str, marker: &str) -> PathBuf {
    let root = dir.join(format!("build-{name}-{version}"));
    std::fs::create_dir_all(root.join("DEBIAN")).unwrap();
    std::fs::create_dir_all(root.join("usr/share").join(name)).unwrap();
    std::fs::write(
        root.join("DEBIAN/control"),
        format!(
            "Package: {name}\nVersion: {version}\nArchitecture: amd64\nMaintainer: Test <test@example.invalid>\nDescription: test package {name}\n generated by aptpod tests\n"
        ),
    )
    .unwrap();
    std::fs::write(root.join("usr/share").join(name).join("marker"), marker).unwrap();
    let out = dir.join(format!("{name}_{version}_amd64.deb"));
    let st = Command::new("dpkg-deb")
        .args(["--root-owner-group", "-Zxz", "--build"])
        .arg(&root)
        .arg(&out)
        .output()
        .unwrap();
    assert!(
        st.status.success(),
        "dpkg-deb: {}",
        String::from_utf8_lossy(&st.stderr)
    );
    out
}

pub struct Server {
    pub child: Child,
    pub url: String,
}

impl Server {
    pub fn start(bin: &Path, cfg: &Path) -> Self {
        let mut child = Command::new(bin)
            .arg("-c")
            .arg(cfg)
            .env("RUST_LOG", "info")
            .stdout(Stdio::piped())
            .stderr(Stdio::inherit())
            .spawn()
            .unwrap();
        let stdout = child.stdout.take().unwrap();
        let (tx, rx) = mpsc::channel();
        std::thread::spawn(move || {
            for line in BufReader::new(stdout).lines().map_while(Result::ok) {
                eprintln!("server: {line}");
                if let Some(addr) = line.split("listening on ").nth(1) {
                    let _ = tx.send(addr.trim().to_string());
                }
            }
        });
        let addr = rx
            .recv_timeout(Duration::from_secs(30))
            .expect("server did not start");
        Server {
            child,
            url: format!("http://{addr}"),
        }
    }

    /// SIGTERM and wait.
    pub fn stop(mut self) -> std::process::ExitStatus {
        Command::new("kill")
            .arg(self.child.id().to_string())
            .status()
            .unwrap();
        for _ in 0..100 {
            if let Some(st) = self.child.try_wait().unwrap() {
                return st;
            }
            std::thread::sleep(Duration::from_millis(100));
        }
        let _ = self.child.kill();
        panic!("server did not stop on SIGTERM");
    }
}

impl Drop for Server {
    fn drop(&mut self) {
        let _ = self.child.kill();
        let _ = self.child.wait();
    }
}

pub struct Cli {
    pub creds: PathBuf,
    pub url: String,
}

impl Cli {
    pub fn run(&self, args: &[&str], stdin: &str) -> Output {
        self.run_env(args, stdin, &[])
    }

    pub fn run_env(&self, args: &[&str], stdin: &str, env: &[(&str, &str)]) -> Output {
        let mut child = Command::new(env!("CARGO_BIN_EXE_aptpod"))
            .args(args)
            .envs(env.iter().copied())
            .env("APTPOD_CREDENTIALS", &self.creds)
            .env("APTPOD_SERVER", &self.url)
            .env_remove("APTPOD_TOKEN")
            .stdin(Stdio::piped())
            .stdout(Stdio::piped())
            .stderr(Stdio::piped())
            .spawn()
            .unwrap();
        child
            .stdin
            .take()
            .unwrap()
            .write_all(stdin.as_bytes())
            .unwrap();
        child.wait_with_output().unwrap()
    }

    pub fn ok(&self, args: &[&str]) -> String {
        let out = self.run(args, "");
        assert!(out.status.success(), "aptpod {args:?}: {}", text(&out));
        String::from_utf8_lossy(&out.stdout).into_owned()
    }

    /// Fails with `code`; returns stderr.
    pub fn fails(&self, args: &[&str], code: i32) -> String {
        let out = self.run(args, "");
        assert_eq!(
            out.status.code(),
            Some(code),
            "aptpod {args:?}: {}",
            text(&out)
        );
        String::from_utf8_lossy(&out.stderr).into_owned()
    }

    pub fn token(&self) -> String {
        let t: toml::Table =
            toml::from_str(&std::fs::read_to_string(&self.creds).unwrap()).unwrap();
        t["token"].as_str().unwrap().to_string()
    }
}

pub fn text(o: &Output) -> String {
    format!(
        "status {:?}\nstdout: {}\nstderr: {}",
        o.status.code(),
        String::from_utf8_lossy(&o.stdout),
        String::from_utf8_lossy(&o.stderr)
    )
}

pub fn api(url: &str, token: &str, method: &str, path: &str, body: Option<Value>) -> (u16, Value) {
    let c = reqwest::blocking::Client::new();
    let mut r = c
        .request(method.parse().unwrap(), format!("{url}{path}"))
        .bearer_auth(token);
    if let Some(b) = body {
        r = r.json(&b);
    }
    let resp = r.send().unwrap();
    let status = resp.status().as_u16();
    (status, resp.json().unwrap_or(Value::Null))
}

pub fn upload(url: &str, token: &str, data: Vec<u8>) -> (u16, Value) {
    let resp = reqwest::blocking::Client::new()
        .post(format!("{url}/api/v1/uploads"))
        .bearer_auth(token)
        .body(data)
        .send()
        .unwrap();
    (resp.status().as_u16(), resp.json().unwrap_or(Value::Null))
}

/// Checks the tools, writes server.toml and adds the users admin, ci
/// (publisher) and viewer (reader), each with password `<name>-password`.
pub fn prepare() -> Option<(tempfile::TempDir, PathBuf, PathBuf)> {
    prepare_extra("")
}

/// [`prepare`] with more server.toml lines.
pub fn prepare_extra(extra: &str) -> Option<(tempfile::TempDir, PathBuf, PathBuf)> {
    let server_bin = PathBuf::from(env!("CARGO_BIN_EXE_aptpod")).with_file_name("aptpod-server");
    if !server_bin.is_file() {
        require("the aptpod-server binary (cargo build --workspace)");
        return None;
    }
    if Command::new("dpkg-deb").arg("--version").output().is_err() {
        require("dpkg-deb");
        return None;
    }
    let dir = tempfile::tempdir().unwrap();
    let d = dir.path();
    let roots = d.join("trees");
    let cfg = d.join("server.toml");
    std::fs::write(
        &cfg,
        format!(
            "listen = \"127.0.0.1:0\"\ndata_dir = {:?}\npublish_roots = [{:?}]\nupload_limit = 1000000\n{extra}",
            d.join("data").display().to_string(),
            roots.display().to_string()
        ),
    )
    .unwrap();
    for (user, role) in [
        ("admin", "admin"),
        ("ci", "publisher"),
        ("viewer", "reader"),
    ] {
        let mut c = Command::new(&server_bin)
            .arg("-c")
            .arg(&cfg)
            .args(["user", "add", user, "--role", role, "--password-stdin"])
            .stdin(Stdio::piped())
            .stdout(Stdio::null())
            .spawn()
            .unwrap();
        c.stdin
            .take()
            .unwrap()
            .write_all(format!("{user}-password\n").as_bytes())
            .unwrap();
        assert!(c.wait().unwrap().success());
    }
    Some((dir, server_bin, cfg))
}

pub fn login(c: &Cli, user: &str) {
    let out = c.run(
        &["login", "--user", user, "--password-stdin"],
        &format!("{user}-password\n"),
    );
    assert!(out.status.success(), "{}", text(&out));
}

/// A throwaway gpg key with a passphrase; `None` (or a panic under
/// APTPOD_REQUIRE_TOOLS) without gpg.
pub struct GpgKey {
    pub home: tempfile::TempDir,
    pub fpr: String,
    pub pass: PathBuf,
    pub public: Vec<u8>,
}

impl GpgKey {
    pub fn new() -> Option<Self> {
        if Command::new("gpg").arg("--version").output().is_err() {
            require("gpg");
            return None;
        }
        // short path: gpg-agent socket names are length limited
        let home = tempfile::Builder::new()
            .prefix("apk")
            .tempdir_in("/tmp")
            .unwrap();
        std::fs::set_permissions(
            home.path(),
            std::os::unix::fs::PermissionsExt::from_mode(0o700),
        )
        .unwrap();
        let pass = home.path().join("pass");
        std::fs::write(&pass, "s3cret-test\n").unwrap();
        let gpg = |args: &[&str]| {
            let out = Command::new("gpg")
                .arg("--homedir")
                .arg(home.path())
                .arg("--batch")
                .args(args)
                .output()
                .unwrap();
            assert!(
                out.status.success(),
                "gpg {args:?}: {}",
                String::from_utf8_lossy(&out.stderr)
            );
            out.stdout
        };
        gpg(&[
            "--pinentry-mode",
            "loopback",
            "--passphrase-file",
            pass.to_str().unwrap(),
            "--quick-gen-key",
            "aptpod test <test@example.invalid>",
            "ed25519",
            "sign",
            "never",
        ]);
        let list = String::from_utf8(gpg(&["--with-colons", "--list-secret-keys"])).unwrap();
        let fpr = list
            .lines()
            .find(|l| l.starts_with("fpr:"))
            .unwrap()
            .split(':')
            .nth(9)
            .unwrap()
            .to_string();
        let public = gpg(&["--export", &fpr]);
        Some(Self {
            home,
            fpr,
            pass,
            public,
        })
    }

    pub fn signing_toml(&self, key: &str) -> String {
        format!(
            "\n[signing]\nkey = {key:?}\nhomedir = {:?}\npassphrase_file = {:?}\n",
            self.home.path().display().to_string(),
            self.pass.display().to_string()
        )
    }
}

impl Drop for GpgKey {
    fn drop(&mut self) {
        let _ = Command::new("gpgconf")
            .arg("--homedir")
            .arg(self.home.path())
            .args(["--kill", "all"])
            .status();
    }
}

/// Serves `root` over HTTP (GET only, no ranges) for mirror tests; pool
/// files are answered after `delay`.
pub fn static_server(root: PathBuf, delay: Duration) -> String {
    let listener = std::net::TcpListener::bind("127.0.0.1:0").unwrap();
    let url = format!("http://{}/", listener.local_addr().unwrap());
    std::thread::spawn(move || {
        for conn in listener.incoming().flatten() {
            let root = root.clone();
            std::thread::spawn(move || {
                let mut reader = BufReader::new(conn.try_clone().unwrap());
                let mut line = String::new();
                let _ = reader.read_line(&mut line);
                loop {
                    let mut h = String::new();
                    if reader.read_line(&mut h).unwrap_or(0) == 0 || h == "\r\n" {
                        break;
                    }
                }
                let path = line.split_whitespace().nth(1).unwrap_or("/");
                let rel = path
                    .trim_start_matches('/')
                    .replace("%2B", "+")
                    .replace("%7E", "~");
                let file = root.join(&rel);
                if rel.starts_with("pool/") {
                    std::thread::sleep(delay);
                }
                let mut out = conn;
                match std::fs::read(&file) {
                    Ok(data) if !rel.contains("..") && file.is_file() => {
                        let _ = write!(
                            out,
                            "HTTP/1.1 200 OK\r\nContent-Length: {}\r\nConnection: close\r\n\r\n",
                            data.len()
                        );
                        let _ = out.write_all(&data);
                    }
                    _ => {
                        let _ = out.write_all(
                            b"HTTP/1.1 404 Not Found\r\nContent-Length: 0\r\nConnection: close\r\n\r\n",
                        );
                    }
                }
            });
        }
    });
    url
}

/// An rsync daemon serving `root` as module `up`; `None` without rsync.
pub fn rsync_daemon(root: &Path, dir: &Path) -> Option<(Child, String)> {
    use std::io::Read;
    if Command::new("rsync").arg("--version").output().is_err() {
        require("rsync");
        return None;
    }
    let conf = dir.join("rsyncd.conf");
    std::fs::write(
        &conf,
        format!(
            "use chroot = no\n[up]\npath = {}\nread only = yes\n",
            root.display()
        ),
    )
    .unwrap();
    for _ in 0..10 {
        let port = std::net::TcpListener::bind("127.0.0.1:0")
            .unwrap()
            .local_addr()
            .unwrap()
            .port();
        let mut child = Command::new("rsync")
            .args(["--daemon", "--no-detach", "--address=127.0.0.1"])
            .arg(format!("--port={port}"))
            .arg(format!("--config={}", conf.display()))
            // stdin must not be a socket: rsync would serve it inetd-style
            // instead of listening.
            .stdin(std::process::Stdio::null())
            .spawn()
            .unwrap();
        for _ in 0..100 {
            if child.try_wait().unwrap().is_some() {
                break;
            }
            if let Ok(mut c) = std::net::TcpStream::connect(("127.0.0.1", port)) {
                let _ = c.set_read_timeout(Some(Duration::from_millis(500)));
                let mut buf = [0u8; 8];
                if c.read_exact(&mut buf).is_ok() && &buf == b"@RSYNCD:" {
                    return Some((child, format!("rsync://127.0.0.1:{port}/up/")));
                }
            }
            std::thread::sleep(Duration::from_millis(50));
        }
        let _ = child.kill();
        let _ = child.wait();
    }
    panic!("rsync daemon did not start");
}

/// A signed upstream archive (dist noble, main, amd64) under `dir`;
/// returns (archive root, binary public key).
pub fn signed_upstream(dir: &Path) -> Option<(PathBuf, Vec<u8>, aptpod_core::testutil::TestKey)> {
    use aptpod_core::deb::read_deb;
    use aptpod_core::index::ReleaseMeta;
    use aptpod_core::publish::{ComponentSpec, DistSpec, PublishPackage, publish_dist};
    let key = aptpod_core::testutil::TestKey::new()?;
    let archive = dir.join("archive");
    let deb = aptpod_core::testutil::build_deb(dir, "sched-pkg", "1.0", "amd64", "xz", "");
    let spec = DistSpec {
        name: "noble".into(),
        meta: ReleaseMeta::new("noble", "Up", "up"),
        architectures: vec!["amd64".into()],
        components: vec![ComponentSpec {
            name: "main".into(),
            packages: vec![PublishPackage {
                info: read_deb(&deb).unwrap(),
                file: deb.clone(),
                mode: Default::default(),
            }],
        }],
    };
    publish_dist(&archive, &spec, Some(&key.signer())).unwrap();
    let public = key.public.clone();
    Some((archive, public, key))
}
